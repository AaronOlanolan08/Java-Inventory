    private void deleteButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_deleteButtonActionPerformed
        Users dellog = new Users();
        if (logsTable.getSelectedRow() < 0)
            JOptionPane.showMessageDialog(this, "Please select an entry from the table you wish to delete.");
        else {
            int opt = JOptionPane.showConfirmDialog(
                    this,
                    "Are you sure you want to delete this log from the database?",
                    "Confirmation",
                    JOptionPane.YES_NO_OPTION);
            if (opt == JOptionPane.YES_OPTION) {
                backupDeletedRow(logsTable.getSelectedRow());
                dellog.deleteLogDAO(Integer.parseInt(
                        logsTable.getValueAt(logsTable.getSelectedRow(), 0).toString()));
                loadDataSet();
            }
        }
    }//GEN-LAST:event_deleteButtonActionPerformed

