    public void loadDataSet() {
        try {
            Users logs = new Users();
            String[] columnNames = {"Log ID", "Name", "Login Time", "Logout Time"};
            logsTable.setModel(logs.buildTableModel(logs.getUserLogsDAO(), columnNames));
        } catch (SQLException e) {
            e.printStackTrace();
        }
    }

    public void loadSearchData(String searchText) {
        try {
            Users logs = new Users();
            String[] columnNames = {"Log ID", "Name", "Login Time", "Logout Time"};
            logsTable.setModel(logs.buildTableModel(logs.getLogsSearch(searchText), columnNames));
        } catch (SQLException e) {
            e.printStackTrace();
        }
    }

    private void backupDeletedRow(int selectedRow) {
        int columnCount = logsTable.getColumnCount();
        Object[] row = new Object[columnCount];
        for (int i = 0; i < columnCount; i++) {
            row[i] = logsTable.getValueAt(selectedRow, i);
        }
        // Save the row to the file
        saveDeletedRowToFile(row);
    }

    private void saveDeletedRowToFile(Object[] row) {
        try (BufferedWriter writer = new BufferedWriter(new FileWriter(DELETED_RECORDS_FILE, true))) {
            StringBuilder sb = new StringBuilder();
            for (Object value : row) {
                sb.append(value).append("\t");
            }
            writer.write(sb.toString().trim());
            writer.newLine();
        } catch (IOException e) {
            e.printStackTrace();
        }
    }

